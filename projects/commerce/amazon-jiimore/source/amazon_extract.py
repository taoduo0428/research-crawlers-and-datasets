"""Pure HTML parsing helpers for Amazon product and review pages.

The module intentionally has no browser, network, cookie, or filesystem side
 effects.  The browser runner can use these functions to turn a captured page
 into the CSV-shaped records used by the original crawler.
"""
from __future__ import annotations

import re
from html import unescape
from urllib.parse import urljoin, urlparse

from lxml import html as lxml_html
from lxml.html import HtmlElement

PRODUCT_FIELDS = [
    "ASIN",
    "链接",
    "标题",
    "评分",
    "评分数",
    "标签",
    "价格",
    "amazon global shipping",
    "商品介绍",
    "Customers say",
]

REVIEW_FIELDS = ["ASIN", "评论用户名", "评论简要", "评论内容"]

CUSTOMER_TAG_FIELDS = [
    "ASIN",
    "标签",
    "标签属性",
    "customers_mention",
    "positive",
    "negative",
    "标签内容",
]

_HIDDEN_CLASS_TOKENS = {
    "aok-hidden",
    "hidden",
    "hide",
    "invisible",
    "visually-hidden",
}
_SKIP_TAGS = {"script", "style", "noscript", "template"}
_MAIN_IDS = {
    "dp-container",
    "ppd",
    "centercol",
    "product-main",
    "productdetails",
    "product-detail",
    "product-information",
    "product-page",
}


def _parse_document(source: str | bytes | HtmlElement) -> HtmlElement:
    if isinstance(source, HtmlElement):
        return source
    if source is None:
        source = ""
    if isinstance(source, bytes):
        return lxml_html.fromstring(source or b"<html></html>")
    text = str(source)
    return lxml_html.fromstring(text or "<html></html>")


def _classes(node: HtmlElement) -> set[str]:
    return set((node.get("class") or "").split())


def _is_hidden(node: HtmlElement) -> bool:
    current: HtmlElement | None = node
    while current is not None:
        if (current.get("aria-hidden") or "").strip().lower() == "true":
            return True
        if _classes(current) & _HIDDEN_CLASS_TOKENS:
            return True
        style = (current.get("style") or "").replace(" ", "").lower()
        if "display:none" in style or "visibility:hidden" in style:
            return True
        current = current.getparent()
    return False


def _is_icon(node: HtmlElement) -> bool:
    classes = _classes(node)
    tag = node.tag.lower() if isinstance(node.tag, str) else ""
    if tag in {"i", "svg", "img"}:
        return True
    return any(
        token == "a-icon"
        or token.startswith("a-icon-")
        or token in {"a-letter-space", "review-rating", "star-rating"}
        for token in classes
    )


def _visible_text(node: HtmlElement, *, exclude_icons: bool = False) -> str:
    """Return visible text while ignoring hidden/duplicated Amazon UI slots."""

    pieces: list[str] = []

    def walk(element: HtmlElement) -> None:
        tag = element.tag.lower() if isinstance(element.tag, str) else ""
        if _is_hidden(element) or tag in _SKIP_TAGS:
            return
        if exclude_icons and _is_icon(element):
            return
        if element.text:
            pieces.append(element.text)
        for child in element:
            walk(child)
            if child.tail and not _is_hidden(child):
                pieces.append(child.tail)

    walk(node)
    text = unescape("".join(pieces))
    text = text.replace("\xa0", " ").replace("\u200b", "")
    # Keep deliberate paragraph breaks, but collapse indentation and duplicate
    # whitespace generated by Amazon's pretty-printed HTML.
    lines = [re.sub(r"[ \t\r\f\v]+", " ", line).strip() for line in text.splitlines()]
    lines = [line for line in lines if line]
    return "\n".join(lines).strip()


def _first_visible(nodes: list[HtmlElement], *, exclude_icons: bool = False) -> str:
    for node in nodes:
        if _is_hidden(node):
            continue
        value = _visible_text(node, exclude_icons=exclude_icons)
        if value:
            return value
    return ""


def _slot_text(container: HtmlElement, names: tuple[str, ...] = (
    "cr-translated-review-content",
    "cr-original-review-content",
)) -> str:
    for name in names:
        nodes = container.xpath(
            './/*[contains(concat(" ", normalize-space(@class), " "), " %s ")]' % name
        )
        value = _first_visible(nodes, exclude_icons=True)
        if value:
            return value
    return ""


def _review_nodes(doc: HtmlElement) -> list[HtmlElement]:
    result: list[HtmlElement] = []
    seen: set[str] = set()
    for node in doc.xpath('//*[@data-hook="review"]'):
        # Some captures contain a wrapper and a nested review node.  Keep only
        # the outermost data-hook node so hidden slots are not double-counted.
        if any(parent.get("data-hook") == "review" for parent in node.iterancestors()):
            continue
        review_id = _review_id(node)
        key = review_id or str(id(node))
        if key not in seen:
            seen.add(key)
            result.append(node)
    return result


def _review_id(node: HtmlElement) -> str:
    raw = (node.get("id") or "").strip()
    if raw.endswith("-review-card"):
        raw = raw[: -len("-review-card")]
    if raw.startswith("customer_review-"):
        raw = raw[len("customer_review-") :]
    return raw


def _class_xpath(class_name: str) -> str:
    return './/*[contains(concat(" ", normalize-space(@class), " "), " %s ")]' % class_name


def _review_title_node(node: HtmlElement) -> HtmlElement | None:
    found = node.xpath('.//*[@data-hook="review-title"]')
    if found:
        return found[0]
    candidates = node.xpath(
        './/*[contains(@class, "review-title") and not(contains(@class, "cr-lightbox"))]'
    )
    return candidates[0] if candidates else None


def _review_body_node(node: HtmlElement) -> HtmlElement | None:
    found = node.xpath('.//*[@data-hook="review-body"]')
    if found:
        return found[0]
    candidates = node.xpath(
        './/*[contains(@class, "review-body") and not(contains(@class, "cr-lightbox"))]'
    )
    if not candidates:
        candidates = node.xpath(
            './/*[contains(@class, "review-text-content") and not(contains(@class, "cr-lightbox"))]'
        )
    return candidates[0] if candidates else None


def extract_reviews(html: str, asin: str) -> list[dict]:
    """Extract valid review rows from one captured review page.

    Translation slots win when visible; hidden translation/original slots are
    ignored.  When those slots do not exist, the visible title/body text is
    used as a fallback.  Reviews with an empty body are deliberately omitted.
    """

    doc = _parse_document(html)
    rows: list[dict] = []
    seen: set[tuple[str, str, str, str]] = set()

    for review in _review_nodes(doc):
        body_node = _review_body_node(review)
        if body_node is None:
            continue
        body = _slot_text(body_node)
        if not body:
            body = _visible_text(body_node, exclude_icons=True)
        if not body:
            continue

        title_node = _review_title_node(review)
        title = ""
        if title_node is not None:
            title = _slot_text(title_node)
            if not title:
                title = _visible_text(title_node, exclude_icons=True)

        profile_nodes = review.xpath(
            './/*[contains(concat(" ", normalize-space(@class), " "), " a-profile-name ")]'
        )
        username = _first_visible(profile_nodes, exclude_icons=True)
        review_id = _review_id(review)
        dedupe_key = (review_id, username, title, body)
        if dedupe_key in seen:
            continue
        seen.add(dedupe_key)

        row = {
            "ASIN": asin,
            "评论用户名": username,
            "评论简要": title,
            "评论内容": body,
        }
        if review_id:
            row["_review_id"] = review_id
        rows.append(row)
    return rows


def _amazon_host(url: str) -> str:
    try:
        return (urlparse(url).hostname or "").lower()
    except ValueError:
        return ""


def _same_site(candidate: str, base_url: str) -> bool:
    candidate_host = _amazon_host(candidate)
    base_host = _amazon_host(base_url)
    if not candidate_host or not base_host:
        return False
    return candidate_host == base_host


def _review_path_matches(url: str, asin: str) -> bool:
    path = urlparse(url).path.rstrip("/")
    match = re.search(r"/product-reviews/([^/]+)", path, flags=re.IGNORECASE)
    return bool(match and match.group(1).upper() == asin.upper())


def _valid_review_url(href: str, asin: str, base_url: str) -> str | None:
    if not href:
        return None
    candidate = urljoin(base_url, unescape(href.strip()))
    parsed = urlparse(candidate)
    if parsed.scheme not in {"http", "https"}:
        return None
    if not _same_site(candidate, base_url):
        return None
    if not _review_path_matches(candidate, asin):
        return None
    return candidate


def find_review_url(html: str, asin: str, base_url: str) -> str | None:
    """Find a same-site review URL for the current ASIN, excluding recommendations."""

    doc = _parse_document(html)
    candidates: list[str] = []
    for anchor in doc.xpath('//a[@href]'):
        href = anchor.get("href") or ""
        if "/product-reviews/" in href.lower():
            candidates.append(href)
    # A product capture can have no rendered link but still expose the review
    # page through its canonical URL.
    for link in doc.xpath('//link[@href]'):
        href = link.get("href") or ""
        if "/product-reviews/" in href.lower():
            candidates.append(href)
    for href in candidates:
        valid = _valid_review_url(href, asin, base_url)
        if valid:
            return valid
    return None


def find_next_review_url(html: str, asin: str, base_url: str) -> str | None:
    """Find the DOM's next-page link for this ASIN only."""

    doc = _parse_document(html)
    candidates: list[HtmlElement] = []
    # Prefer Amazon's actual pagination last item and rel=next.  The generic
    # fallback is intentionally restricted to pagination-ish class/labels.
    candidates.extend(
        doc.xpath(
            '//ul[contains(concat(" ", normalize-space(@class), " "), " a-pagination ")]'
            '//li[contains(concat(" ", normalize-space(@class), " "), " a-last ")]//a[@href]'
        )
    )
    candidates.extend(doc.xpath('//a[@rel="next"][@href]'))
    candidates.extend(
        doc.xpath(
            '//a[@href and (contains(translate(normalize-space(.), '
            '"ABCDEFGHIJKLMNOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz"), "next") '
            'or contains(@aria-label, "下一页") or contains(@aria-label, "Next"))]'
        )
    )
    seen: set[str] = set()
    for anchor in candidates:
        href = anchor.get("href") or ""
        if href in seen:
            continue
        seen.add(href)
        valid = _valid_review_url(href, asin, base_url)
        if valid:
            return valid
    return None


def page_status(html: str, url: str) -> str:
    """Classify a captured page without treating a navigation Sign in link as login."""

    doc = _parse_document(html)
    path = (urlparse(url).path or "").lower()
    title_text = _query_visible(doc, ["//title", "//h1", "//h2"], exclude_icons=True).lower()
    challenge_markers = (
        "captcha",
        "robot check",
        "enter the characters you see",
        "verify you are human",
        "验证您不是机器人",
        "人机验证",
    )
    challenge_nodes = doc.xpath(
        '//*[@id="auth-captcha-image" or @id="captchacharacters" or '
        '@name="captchacharacters" or @name="captcha" or '
        'contains(translate(@class, "ABCDEFGHIJKLMNOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz"), "captcha")]'
    )
    challenge_forms = doc.xpath(
        '//form[contains(translate(@action, "ABCDEFGHIJKLMNOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz"), "captcha") '
        'or contains(translate(@action, "ABCDEFGHIJKLMNOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz"), "validate")]'
    )
    challenge_url = "captcha" in path or "validatecaptcha" in path
    if challenge_nodes or challenge_forms or challenge_url or any(marker in title_text for marker in challenge_markers):
        return "challenge"

    login_path = (
        "/ap/signin" in path
        or path.endswith("/signin")
        or "/gp/sign-in" in path
    )
    login_forms = doc.xpath(
        '//form[.//input[@name="email" or @id="ap_email"] and '
        './/input[@name="password" or @id="ap_password"]]'
    )
    if login_path or login_forms:
        return "login_required"
    return "ready"


def _main_product_node(doc: HtmlElement) -> HtmlElement:
    title_nodes = doc.xpath('//*[@id="productTitle"]')
    if title_nodes:
        title = title_nodes[0]
        for ancestor in title.iterancestors():
            element_id = (ancestor.get("id") or "").lower()
            if element_id in _MAIN_IDS or any(token in element_id for token in ("product-main", "dp-container", "centercol")):
                return ancestor
        # An element with the product title is safer than the full document,
        # while still allowing fixtures with a custom product-root id.
        for ancestor in title.iterancestors():
            ancestor_tag = ancestor.tag.lower() if isinstance(ancestor.tag, str) else ""
            if ancestor_tag in {"div", "main", "section"} and ancestor.get("id"):
                return ancestor
    for element_id in _MAIN_IDS:
        found = doc.xpath('//*[@id="%s"]' % element_id)
        if found:
            return found[0]
    return doc


def _relative_xpath(expression: str) -> str:
    # XPath expressions passed to a subtree must be relative; an expression
    # beginning with // would otherwise escape the selected product root.
    return "." + expression if expression.startswith("//") else expression


def _query_visible(root: HtmlElement, expressions: list[str], *, exclude_icons: bool = False) -> str:
    for expression in expressions:
        nodes = root.xpath(_relative_xpath(expression))
        value = _first_visible(nodes, exclude_icons=exclude_icons)
        if value:
            return value
    return ""


def _parse_rating(text: str) -> str:
    match = re.search(r"(?<!\d)(\d+(?:[.,]\d+)?)(?:\s*(?:颗星|out of|stars?))?", text)
    return match.group(1).replace(",", ".") if match else ""


def _parse_count(text: str) -> int | str:
    match = re.search(r"(?<!\d)(\d[\d,\s]*)(?!\d)", text)
    if not match:
        return ""
    digits = re.sub(r"[^0-9]", "", match.group(1))
    return int(digits) if digits else ""


def _has_class(node: HtmlElement, token: str) -> bool:
    return token in _classes(node)


def _price_is_excluded(node: HtmlElement) -> bool:
    """Reject list-price, installment and other non-payable price nodes."""

    current: HtmlElement | None = node
    while current is not None:
        classes = _classes(current)
        element_id = (current.get("id") or "").lower()
        if classes & {
            "a-text-price",
            "apex-basisprice-value",
            "basisprice",
            "installment",
            "installments",
        }:
            return True
        if any(token in element_id for token in ("price-block-amount", "installment", "payment-plan")):
            return True
        current = current.getparent()
    return False


def _price_component_text(nodes: list[HtmlElement]) -> str:
    # Price components can be aria-hidden for screen readers while still
    # containing the visible numeric price. The enclosing price was checked.
    for node in nodes:
        if node.get("hidden") is not None or "aok-hidden" in _classes(node):
            continue
        if re.search(r"display\s*:\s*none|visibility\s*:\s*hidden", node.get("style", ""), re.I):
            continue
        value = "".join(node.itertext()).strip()
        if value:
            return value
    return ""


def _price_from_node(node: HtmlElement) -> str:
    if _is_hidden(node) or _price_is_excluded(node):
        return ""

    # When the matched node itself is Amazon's semantic offscreen value,
    # read its own text; the descendant-only query below would otherwise miss it.
    if "a-offscreen" in _classes(node):
        value = _visible_text(node)
        if value and re.search(r"\d", value):
            return value

    # Prefer Amazon's semantic offscreen value when it contains a real amount.
    for offscreen in node.xpath('.//*[contains(concat(" ", normalize-space(@class), " "), " a-offscreen ")]'):
        value = _visible_text(offscreen)
        if value and re.search(r"\d", value):
            return value

    # Amazon sometimes leaves .a-offscreen blank and exposes whole/fraction
    # spans instead.  Rebuild the same payable price without using list or
    # installment siblings.
    whole_nodes = node.xpath(
        './/*[contains(concat(" ", normalize-space(@class), " "), " a-price-whole ")]'
    )
    fraction_nodes = node.xpath(
        './/*[contains(concat(" ", normalize-space(@class), " "), " a-price-fraction ")]'
    )
    whole = _price_component_text(whole_nodes)
    fraction = _price_component_text(fraction_nodes)
    if whole:
        whole = re.sub(r"[^0-9,]", "", whole).rstrip(",")
        fraction = re.sub(r"[^0-9]", "", fraction)
        symbol_nodes = node.xpath(
            './/*[contains(concat(" ", normalize-space(@class), " "), " a-price-symbol ")]'
        )
        symbol = _price_component_text(symbol_nodes)
        if fraction:
            return f"{symbol}{whole}.{fraction}"
        return f"{symbol}{whole}"
    return ""


def _price_text(root: HtmlElement) -> str:
    # Payable price containers first.  The order matters: Amazon also renders
    # list price and monthly installment amounts nearby.
    expressions = [
        '//*[@id="corePriceDisplay_desktop_feature_div"]//*[contains(concat(" ", normalize-space(@class), " "), " priceToPay ") and contains(concat(" ", normalize-space(@class), " "), " apex-pricetopay-value ")] ',
        '//*[@id="corePrice_feature_div"]//*[contains(concat(" ", normalize-space(@class), " "), " apex-pricetopay-value ")] ',
        '//*[@id="corePriceDisplay_desktop_feature_div"]//*[contains(concat(" ", normalize-space(@class), " "), " apex-pricetopay-value ")] ',
        '//*[@id="apex_desktop"]//*[contains(concat(" ", normalize-space(@class), " "), " priceToPay ")] ',
        '//*[@id="priceblock_ourprice"]',
        '//*[@id="priceblock_dealprice"]',
        '//*[@id="price_inside_buybox"]',
        '//*[@id="corePrice_feature_div"]//*[contains(concat(" ", normalize-space(@class), " "), " a-offscreen ")] ',
    ]
    for expression in expressions:
        for node in root.xpath(_relative_xpath(expression)):
            value = _price_from_node(node)
            if value:
                return value
    return ""


def extract_customer_tags(html: str, asin: str) -> list[dict]:
    """Extract Customers say aspect rows when both button and detail are present."""

    doc = _parse_document(html)
    cards = doc.xpath('//*[@id="cr-product-insights-cards"]')
    if not cards:
        return []
    card = cards[0]
    group = card.xpath('.//*[@id="aspect-button-group-0"]')
    if not group:
        return []
    buttons = [button for button in group[0].xpath('.//button') if not _is_hidden(button)]
    sheets = [
        node
        for node in card.xpath(
            './/*[contains(@class, "insight-bottom-sheet-content")]'
        )
        if not _is_hidden(node)
    ]
    rows: list[dict] = []
    for index, button in enumerate(buttons):
        label = _visible_text(button, exclude_icons=True)
        if not label:
            continue
        target_id = button.get("aria-controls") or button.get("data-target")
        sheet = None
        if target_id:
            matched = card.xpath('.//*[@id=%s]' % repr(target_id))
            if matched:
                sheet = matched[0]
        if sheet is None and index < len(sheets):
            sheet = sheets[index]
        if sheet is None:
            continue

        detail_text = _visible_text(sheet, exclude_icons=True)
        if not detail_text:
            continue
        attr = "0"
        fills = sheet.xpath('.//*[local-name()="path"]/@fill | .//*[local-name()="svg"]/@fill')
        if not fills:
            fills = button.xpath('.//*[local-name()="path"]/@fill | .//*[local-name()="svg"]/@fill')
        if fills:
            fill = fills[0]
            attr = "1" if fill == "#067D62" else "-1" if fill == "#DE7921" else fill

        def metric(label_text: str) -> str:
            match = re.search(
                rf"{re.escape(label_text)}\s*[:：]?\s*([0-9][0-9,]*)",
                detail_text,
                flags=re.IGNORECASE,
            )
            return match.group(1).replace(",", "") if match else ""

        content_nodes = sheet.xpath('.//p')
        content = _first_visible(content_nodes, exclude_icons=True) if content_nodes else detail_text
        rows.append(
            {
                "ASIN": asin,
                "标签": label,
                "标签属性": attr,
                "customers_mention": metric("customers mention"),
                "positive": metric("positive"),
                "negative": metric("negative"),
                "标签内容": content,
            }
        )
    return rows


def extract_product(html: str, asin: str, url: str) -> dict:
    """Extract the original ten product columns from the main product area."""

    doc = _parse_document(html)
    root = _main_product_node(doc)
    item = {field: "" for field in PRODUCT_FIELDS}
    item["ASIN"] = asin
    item["链接"] = url

    item["标题"] = _query_visible(root, ['//*[@id="productTitle"]'])
    rating_text = _query_visible(
        root,
        [
            '//*[@id="averageCustomerReviews"]//*[contains(@class, "a-icon-alt")] ',
            '//*[@id="acrPopover"]//*[contains(@class, "a-icon-alt")] ',
            '//*[contains(@class, "averageStarRating")]//*[contains(@class, "a-icon-alt")] ',
        ],
        # The rating is deliberately stored in an a-icon-alt span; do not
        # apply the generic icon filter to this specific field.
        exclude_icons=False,
    )
    item["评分"] = _parse_rating(rating_text)
    count_text = _query_visible(
        root,
        ['//*[@id="acrCustomerReviewText"]', '//*[@id="acrCustomerReviewLink"]'],
        exclude_icons=True,
    )
    item["评分数"] = _parse_count(count_text)
    item["价格"] = _price_text(root)
    item["标签"] = _query_visible(
        root,
        [
            '//*[@id="acBadge_feature_div"]',
            '//*[contains(@class, "ac-badge-text")] ',
            '//*[contains(@class, "a-badge-label")] ',
        ],
        exclude_icons=True,
    )

    shipping_candidates = root.xpath(
        './/*[contains(translate(@id, "ABCDEFGHIJKLMNOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz"), "global-shipping") '
        'or contains(translate(@class, "ABCDEFGHIJKLMNOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz"), "global-shipping") '
        'or contains(concat(" ", normalize-space(@class), " "), " a-lineitem ")]'
    )
    for node in shipping_candidates:
        text = _visible_text(node, exclude_icons=True)
        if text and re.search(r"shipping|delivery|配送|运费", text, flags=re.IGNORECASE):
            item["amazon global shipping"] = text
            break

    item["商品介绍"] = _query_visible(
        root,
        [
            '//*[@id="feature-bullets"]',
            '//*[@id="productDescription"]',
            '//*[@id="bookDescription_feature_div"]',
            '//*[contains(@class, "a-unordered-list") and contains(@class, "a-spacing-mini")] ',
        ],
        exclude_icons=True,
    )

    cards = root.xpath('.//*[@id="cr-product-insights-cards"]')
    if cards:
        summary = _query_visible(cards[0], ['.//*[contains(@class, "a-spacing-small")]'], exclude_icons=True)
        item["Customers say"] = summary
    return item


